"""Render report data as PDF (ReportLab) or CSV."""

import csv
import io

from reportlab.graphics.charts.lineplots import LinePlot
from reportlab.graphics.shapes import Drawing, String
from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.services.clock import parse

NAVY = colors.HexColor("#0B1F3A")
SLATE = colors.HexColor("#5B6B82")
LINE = colors.HexColor("#DCE3EC")
SOFT = colors.HexColor("#F4F7FB")
RED = colors.HexColor("#C8281E")
AMBER = colors.HexColor("#B45309")
TEAL = colors.HexColor("#0E9F6E")
BLUE = colors.HexColor("#0369A1")

PARAM_LABELS = {"hr": "Heart rate (bpm)", "spo2": "SpO2 (%)", "rr": "Resp. rate (/min)", "sys": "Systolic (mmHg)", "dia": "Diastolic (mmHg)"}


def clean(value) -> str:
    """Standard PDF fonts lack a few glyphs; replace them with ASCII equivalents."""
    if value is None:
        return "—"
    text = str(value)
    return text.replace("₂", "2").replace("→", "->").replace("“", '"').replace("”", '"')


def fmt_time(value: str | None) -> str:
    if not value:
        return "—"
    dt = parse(value)
    return dt.strftime("%d %b %H:%M") if dt else "—"


# ---------------------------------------------------------------------------- CSV


def render_csv(kind: str, data: dict) -> bytes:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow([f"ACME Clinical — {clean(data['title'])}"])
    w.writerow([f"Window: {data['window']['since']} to {data['window']['until']}", f"Generated by {data.get('generated_by', '')}"])
    w.writerow([])
    if kind == "patient_summary":
        w.writerow(["Hour", "HR avg", "SpO2 avg", "RR avg", "Systolic avg", "Diastolic avg"])
        for r in data["hourly"]:
            w.writerow([r["hour"], r["hr"], r["spo2"], r["rr"], r["sys"], r["dia"]])
        w.writerow([])
    if kind == "shift_summary":
        w.writerow(["Bed", "Patient", "Acuity", "Monitored", "HR avg", "SpO2 min", "RR max", "Systolic range", "Clinical alarms"])
        for r in data["patients"]:
            w.writerow([r["bed"], r["patient"], r["acuity"], "yes" if r["monitored"] else "no", r["hr_avg"], r["spo2_min"],
                        r["rr_max"], r["sys_range"], r["clinical_alarms"]])
        w.writerow([])
    if kind == "device_status":
        cols = ["serial", "asset_tag", "model", "firmware", "status", "bed", "connection", "sensor", "battery_pct",
                "next_service_due", "technical_alarms", "open_work_orders"]
        w.writerow([c.replace("_", " ").title() for c in cols])
        for r in data["devices"]:
            w.writerow([r[c] for c in cols])
        return buf.getvalue().encode("utf-8-sig")
    cols = ["started_at", "type", "severity", "category", "bed", "patient", "monitor", "message", "state",
            "acknowledged_by", "acknowledged_at", "resolved_at"]
    w.writerow([c.replace("_", " ").title() for c in cols])
    for r in data.get("alarms", []):
        w.writerow([clean(r[c]) if c in ("message", "type") else r[c] for c in cols])
    return buf.getvalue().encode("utf-8-sig")


# ---------------------------------------------------------------------------- PDF

styles = getSampleStyleSheet()
H1 = ParagraphStyle("h1", parent=styles["Heading1"], textColor=NAVY, fontSize=18, spaceAfter=2, leading=22)
H2 = ParagraphStyle("h2", parent=styles["Heading2"], textColor=NAVY, fontSize=12.5, spaceBefore=10, spaceAfter=6)
BODY = ParagraphStyle("body", parent=styles["BodyText"], textColor=NAVY, fontSize=9, leading=12, alignment=TA_LEFT)
MUTED = ParagraphStyle("muted", parent=BODY, textColor=SLATE, fontSize=8.5)
CELL = ParagraphStyle("cell", parent=BODY, fontSize=8, leading=10)


def _table(header: list[str], rows: list[list], widths: list[float] | None = None) -> Table:
    data = [[Paragraph(f"<b>{clean(h)}</b>", CELL) for h in header]]
    for r in rows:
        data.append([Paragraph(clean(c), CELL) for c in r])
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), SOFT),
        ("LINEBELOW", (0, 0), (-1, 0), 0.8, NAVY),
        ("LINEBELOW", (0, 1), (-1, -1), 0.3, LINE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    return t


def _kpi_strip(kpis: list[tuple[str, object]], width: float) -> Table:
    cells = [[Paragraph(f"<font size=16><b>{clean(v)}</b></font><br/><font color='#5B6B82' size=7.5>{clean(k)}</font>", BODY)
              for k, v in kpis]]
    t = Table(cells, colWidths=[width / len(kpis)] * len(kpis))
    t.setStyle(TableStyle([
        ("BOX", (0, 0), (-1, -1), 0.6, LINE),
        ("INNERGRID", (0, 0), (-1, -1), 0.6, LINE),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
    ]))
    return t


def _trend_chart(series: list[dict], key: str, label: str, color, width: float) -> Drawing | None:
    pts = [(i, s[key]) for i, s in enumerate(series) if s.get(key) is not None]
    if len(pts) < 2:
        return None
    d = Drawing(width, 120)
    d.add(String(0, 108, clean(label), fontName="Helvetica-Bold", fontSize=9, fillColor=NAVY))
    lp = LinePlot()
    lp.x, lp.y, lp.width, lp.height = 30, 15, width - 40, 85
    lp.data = [pts]
    lp.lines[0].strokeColor = color
    lp.lines[0].strokeWidth = 1.4
    values = [p[1] for p in pts]
    lp.yValueAxis.valueMin = min(values) - 3
    lp.yValueAxis.valueMax = max(values) + 3
    lp.yValueAxis.labels.fontSize = 7
    lp.xValueAxis.visible = False
    lp.yValueAxis.strokeColor = LINE
    d.add(lp)
    return d


def render_pdf(kind: str, data: dict) -> bytes:
    buf = io.BytesIO()
    wide = kind in ("alarm_log", "device_status")
    pagesize = landscape(A4) if wide else A4
    doc = SimpleDocTemplate(buf, pagesize=pagesize, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=18 * mm,
                            bottomMargin=16 * mm, title=clean(data["title"]), author="ACME Clinical")
    width = pagesize[0] - 32 * mm

    def decorate(canvas, _doc):
        canvas.saveState()
        canvas.setFillColor(NAVY)
        canvas.rect(0, pagesize[1] - 8 * mm, pagesize[0], 8 * mm, stroke=0, fill=1)
        canvas.setFillColor(colors.white)
        canvas.setFont("Helvetica-Bold", 9)
        canvas.drawString(16 * mm, pagesize[1] - 5.5 * mm, "ACME Clinical")
        canvas.setFont("Helvetica", 8)
        canvas.drawRightString(pagesize[0] - 16 * mm, pagesize[1] - 5.5 * mm, "Simulated data — not for clinical use")
        canvas.setFillColor(SLATE)
        canvas.drawString(16 * mm, 9 * mm, f"Generated {fmt_time(data.get('generated_at'))} by {clean(data.get('generated_by'))}")
        canvas.drawRightString(pagesize[0] - 16 * mm, 9 * mm, f"Page {_doc.page}")
        canvas.restoreState()

    story = [
        Paragraph(clean(data["title"]), H1),
        Paragraph(f"Reporting window: {fmt_time(data['window']['since'])} to {fmt_time(data['window']['until'])} "
                  f"({data['window']['hours']:g} h, simulation clock)", MUTED),
        Spacer(1, 8),
    ]
    k = data.get("kpis", {})

    if kind == "shift_summary":
        story.append(_kpi_strip([("Alarms", k["alarms_total"]), ("Critical", k["critical"]), ("Still open", k["still_open"]),
                                 ("Unacknowledged", k["unacknowledged"]), ("Escalations", k["escalations"]),
                                 ("Median ack (min)", k["median_ack_minutes"])], width))
        story.append(Paragraph("Patients", H2))
        story.append(_table(["Bed", "Patient", "Acuity", "HR avg", "SpO2 min", "RR max", "Systolic", "Alarms"],
                            [[r["bed"], r["patient"], r["acuity"], r["hr_avg"], r["spo2_min"], r["rr_max"], r["sys_range"],
                              r["clinical_alarms"]] for r in data["patients"]],
                            [18 * mm, 42 * mm, 15 * mm, 18 * mm, 18 * mm, 18 * mm, 24 * mm, 15 * mm]))
        if data["alarms_by_type"]:
            story.append(Paragraph("Alarms by type", H2))
            story.append(_table(["Alarm type", "Count"], [[r["label"], r["count"]] for r in data["alarms_by_type"]],
                                [80 * mm, 25 * mm]))
        if data["alarms"]:
            story.append(Paragraph("Alarm details", H2))
            story.append(_alarm_table(data["alarms"][:80], width, compact=True))

    elif kind == "patient_summary":
        p = data["patient"]
        story.append(_table(["MRN", "Bed", "Diagnosis", "Acuity", "Code status", "Allergies", "Attending"],
                            [[p["mrn"], p["bed"], p["diagnosis"], p["acuity"], p["code_status"], p["allergies"], p["attending"]]]))
        story.append(Spacer(1, 8))
        story.append(_kpi_strip([("Readings", k["readings"]), ("Alarms", k["alarms_total"]), ("Critical", k["critical"]),
                                 ("Still open", k["still_open"]), ("Median ack (min)", k["median_ack_minutes"])], width))
        story.append(Paragraph("Vital sign statistics", H2))
        story.append(_table(["Parameter", "Minimum", "Average", "Maximum"],
                            [[PARAM_LABELS[key], s["min"], s["avg"], s["max"]] if s else [PARAM_LABELS[key], "—", "—", "—"]
                             for key, s in data["stats"].items()], [60 * mm, 30 * mm, 30 * mm, 30 * mm]))
        for key, label, color in (("hr", "Heart rate trend (bpm)", TEAL), ("spo2", "SpO2 trend (%)", BLUE)):
            chart = _trend_chart(data["series"], key, label, color, width)
            if chart:
                story.append(KeepTogether([Spacer(1, 6), chart]))
        if data["hourly"]:
            story.append(Paragraph("Hourly averages", H2))
            story.append(_table(["Hour", "HR", "SpO2", "RR", "Sys", "Dia"],
                                [[r["hour"], r["hr"], r["spo2"], r["rr"], r["sys"], r["dia"]] for r in data["hourly"]]))
        if data["alarms"]:
            story.append(Paragraph("Alarms", H2))
            story.append(_alarm_table(data["alarms"], width, compact=True))
        if data["notes"]:
            story.append(Paragraph("Recent notes", H2))
            story.append(_table(["Time", "Author", "Type", "Note"],
                                [[fmt_time(n["created_at"]), n["author"], n["category"], n["body"]] for n in data["notes"]],
                                [26 * mm, 32 * mm, 22 * mm, width - 80 * mm]))

    elif kind == "device_status":
        story.append(_kpi_strip([("Devices", k["devices"]), ("In use", k["in_use"]), ("Offline", k["offline"]),
                                 ("Low battery", k["low_battery"]), ("In maintenance", k["maintenance"]),
                                 ("Technical alarms", k["technical_alarms"]), ("Open work orders", k["open_work_orders"])], width))
        story.append(Paragraph("Devices", H2))
        story.append(_table(["Serial", "Asset", "Model", "FW", "Status", "Bed", "Connection", "Sensor", "Battery", "Service due",
                             "Tech. alarms", "Work orders"],
                            [[r["serial"], r["asset_tag"], r["model"], r["firmware"], r["status"].replace("_", " "), r["bed"],
                              r["connection"], r["sensor"].replace("_", " "), f"{r['battery_pct']}%", r["next_service_due"],
                              r["technical_alarms"], r["open_work_orders"]] for r in data["devices"]]))
        if data["work_orders"]:
            story.append(Paragraph("Open work orders", H2))
            story.append(_table(["Monitor", "Type", "Status", "Title", "Scheduled"],
                                [[w["monitor"], w["kind"].replace("_", " "), w["status"].replace("_", " "), w["title"], w["scheduled_for"]]
                                 for w in data["work_orders"]], [28 * mm, 35 * mm, 25 * mm, width - 118 * mm, 30 * mm]))
    else:
        story.append(_kpi_strip([("Alarms", k["alarms_total"]), ("Critical", k["critical"]), ("Still open", k["still_open"]),
                                 ("Unacknowledged", k["unacknowledged"])], width))
        story.append(Spacer(1, 8))
        story.append(_alarm_table(data["alarms"], width, compact=False))

    doc.build(story, onFirstPage=decorate, onLaterPages=decorate)
    return buf.getvalue()


def _alarm_table(alarms: list[dict], width: float, compact: bool) -> Table:
    if compact:
        return _table(["Started", "Bed", "Alarm", "Severity", "State", "Acknowledged by"],
                      [[fmt_time(a["started_at"]), a["bed"], a["type"], a["severity"], a["state"], a["acknowledged_by"] or "—"]
                       for a in alarms])
    return _table(["Started", "Bed", "Patient", "Monitor", "Message", "Severity", "State", "Acknowledged", "Resolved"],
                  [[fmt_time(a["started_at"]), a["bed"], a["patient"], a["monitor"], a["message"], a["severity"], a["state"],
                    f"{a['acknowledged_by']} {fmt_time(a['acknowledged_at'])}" if a["acknowledged_by"] else "—",
                    fmt_time(a["resolved_at"]) if a["resolved_at"] else "—"] for a in alarms])
