import { useQuery } from '@tanstack/react-query'
import { Activity } from 'lucide-react'
import { useMemo, useState } from 'react'
import { useProfile } from '../../auth/AuthProvider'
import { AckDialog } from '../../components/alarms/alarmUi'
import { MonitorTile } from '../../components/monitoring/MonitorTile'
import { useWaveformFeed } from '../../components/monitoring/waveformStore'
import { EmptyState, ErrorState, PageHeader, Segmented, Select, Skeleton } from '../../components/ui/primitives'
import { errorMessage } from '../../lib/api'
import { SEVERITY_RANK } from '../../lib/format'
import { overviewService } from '../../services/clinical'
import type { Alarm } from '../../types'

export default function LiveMonitoringScreen() {
  const profile = useProfile()
  const [ward, setWard] = useState('')
  const [order, setOrder] = useState<'bed' | 'priority'>('bed')
  const [ackAlarm, setAckAlarm] = useState<Alarm | null>(null)
  const { data, isLoading, isError, error, refetch } = useQuery({ queryKey: ['live'], queryFn: overviewService.live, refetchInterval: 15_000 })
  const vitalsKey = data?.map((m) => `${m.id}:${m.vitals.hr}:${m.sensor_status}:${m.connection}`).join('|')
  useWaveformFeed(profile.preferences.show_waveforms && !!data?.length, undefined, vitalsKey)

  const wards = useMemo(() => [...new Map((data ?? []).filter((m) => m.bed).map((m) => [m.bed!.ward_id, m.bed!.ward_name])).entries()], [data])
  const monitors = useMemo(() => {
    let list = (data ?? []).filter((m) => !ward || m.bed?.ward_id === ward)
    if (order === 'priority') {
      list = [...list].sort((a, b) => {
        const ra = a.alarms.highest ? SEVERITY_RANK[a.alarms.highest] - (a.alarms.unacknowledged ? 0.5 : 0) : 9
        const rb = b.alarms.highest ? SEVERITY_RANK[b.alarms.highest] - (b.alarms.unacknowledged ? 0.5 : 0) : 9
        return ra - rb
      })
    }
    return list
  }, [data, ward, order])

  return (
    <div>
      <PageHeader
        title="Live monitoring"
        subtitle="Central station view of every bedside monitor. Waveforms are synthetic and generated by the API."
        actions={
          <>
            <Select value={ward} onChange={(e) => setWard(e.target.value)} className="w-auto" aria-label="Ward">
              <option value="">All wards</option>
              {wards.map(([id, name]) => (
                <option key={id} value={id}>
                  {name}
                </option>
              ))}
            </Select>
            <Segmented
              value={order}
              onChange={setOrder}
              items={[
                { value: 'bed', label: 'By bed' },
                { value: 'priority', label: 'By priority' },
              ]}
            />
          </>
        }
      />
      {isError ? (
        <ErrorState message={errorMessage(error)} onRetry={() => void refetch()} />
      ) : isLoading ? (
        <div className="grid gap-4 md:grid-cols-2 2xl:grid-cols-3">
          {Array.from({ length: 6 }, (_, i) => (
            <Skeleton key={i} className="h-[300px] rounded-xl" />
          ))}
        </div>
      ) : !monitors.length ? (
        <EmptyState icon={<Activity className="size-6" />} title="No monitors are assigned" description="Assign a monitor to a bed from the Devices page to start live monitoring." />
      ) : (
        <div className="grid gap-4 md:grid-cols-2 2xl:grid-cols-3">
          {monitors.map((m) => (
            <MonitorTile key={m.id} monitor={m} showWaveforms={profile.preferences.show_waveforms} onAcknowledge={setAckAlarm} />
          ))}
        </div>
      )}
      <AckDialog alarm={ackAlarm} onClose={() => setAckAlarm(null)} />
    </div>
  )
}
